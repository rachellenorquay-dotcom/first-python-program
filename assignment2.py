# Assignment 1.2: Python Data Types

# 1. Create variables for the four basic data types
student_name = "Annie"        # str
course_credits = 3            # int
current_gpa = 3.85            # float
is_enrolled = True            # bool

# 2. Display each variable value
print("Values:")
print(f"Name: {student_name}")
print(f"Credits: {course_credits}")
print(f"GPA: {current_gpa}")
print(f"Enrolled: {is_enrolled}")

print()

# 3. Use type() to display the data type of each variable
print("Data Types:")
print(f"student_name type: {type(student_name)}")
print(f"course_credits type: {type(course_credits)}")
print(f"current_gpa type: {type(current_gpa)}")
print(f"is_enrolled type: {type(is_enrolled)}")